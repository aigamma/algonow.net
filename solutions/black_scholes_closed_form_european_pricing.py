# Puzzle 170: Black-Scholes x Closed-form European pricing
# Option pricing: what is a European call or put worth today, given the
# stock price S, the strike K, the time to expiry T, the risk-free rate r,
# and the volatility sigma? The algorithm is risk-neutral valuation
# (Black and Scholes 1973, Merton 1973): under continuous hedging the
# option's value obeys a partial differential equation with no appetite
# for risk in it, equivalently it is the discounted expected payoff under
# a measure where the stock drifts at the risk-free rate. The heuristic
# is to assume the stock follows geometric Brownian motion with CONSTANT
# volatility, which makes the terminal price lognormal and the expectation
# a closed form: C = S N(d1) - K e^{-rT} N(d2), with d1 and d2 in terms of
# log(S/K), (r + sigma^2 / 2) T, and sigma sqrt(T). Two evaluations of the
# normal distribution function price what a lattice needs a thousand
# steps and a Monte Carlo run a hundred thousand paths to approximate,
# and every sensitivity (delta, gamma, vega, theta, rho) is a formula too.
#
# Referees (one shared instance unless stated: S = 100, K = 100, r = 5%,
# sigma = 20%, T = 1 year):
# (1) THE PDE: the closed form must satisfy the Black-Scholes equation,
#     V_t + sigma^2 S^2 V_SS / 2 + r S V_S - r V = 0, checked by central
#     differences of the formula at a grid of (S, t) points, and the
#     boundary conditions (the payoff at expiry, zero volatility giving the
#     forward intrinsic value, S -> 0 and S -> inf);
# (2) PUT-CALL PARITY, C - P = S - K e^{-rT}, exact to rounding, and the
#     analytic Greeks against central differences of the price;
# (3) THREE NUMERICAL RIVALS converging to the formula with their measured
#     error and work: the Cox-Ross-Rubinstein lattice at 100, 1,000, and
#     4,000 steps (nodes), a Crank-Nicolson finite-difference PDE solver
#     on 200 x 200 and 800 x 800 grids (grid points), and Monte Carlo with
#     exact lognormal terminal draws at 10^4 and 10^5 paths (paths), each
#     reported with its standard error;
# (4) IMPLIED VOLATILITY: the formula inverted by Brent's method recovers
#     the volatility from a price to 1e-10 across strikes 60 to 140, and a
#     smile is MEASURED where the model is wrong: prices generated by a
#     Heston stochastic-volatility simulation (correlation -0.7) at five
#     strikes, inverted through Black-Scholes, give implied volatilities
#     that differ by strike, which a constant-volatility model cannot
#     produce;
# (5) THE NEGATIVE EXAMPLE, measured: the vanilla formula used for an
#     up-and-out barrier call (barrier 120, daily monitoring), against a
#     Monte Carlo price of the actual contract.
#
# AUTHOR CORRECTION: the draft expected Crank-Nicolson on a 200 x 200 grid
# to price within a tenth of a cent. Measured, the error at 200 x 200 is
# about a cent because of the kink in the payoff at the strike (the
# scheme's known oscillation at non-smooth data); the 800 x 800 grid gets
# under a tenth of a cent, and the page reports both.
import math
import random

SEED = 20261010
S0, K0, R0, SIG0, T0 = 100.0, 100.0, 0.05, 0.20, 1.0


def ncdf(x):
    return 0.5 * math.erfc(-x / math.sqrt(2))


def npdf(x):
    return math.exp(-0.5 * x * x) / math.sqrt(2 * math.pi)


def d1d2(S, K, r, sigma, T):
    st = sigma * math.sqrt(T)
    d1 = (math.log(S / K) + (r + 0.5 * sigma * sigma) * T) / st
    return d1, d1 - st


def bs_call(S, K, r, sigma, T):
    if T <= 0:
        return max(S - K, 0.0)
    if sigma <= 0:
        return max(S - K * math.exp(-r * T), 0.0)
    d1, d2 = d1d2(S, K, r, sigma, T)
    return S * ncdf(d1) - K * math.exp(-r * T) * ncdf(d2)


def bs_put(S, K, r, sigma, T):
    if T <= 0:
        return max(K - S, 0.0)
    if sigma <= 0:
        return max(K * math.exp(-r * T) - S, 0.0)
    d1, d2 = d1d2(S, K, r, sigma, T)
    return K * math.exp(-r * T) * ncdf(-d2) - S * ncdf(-d1)


def greeks_call(S, K, r, sigma, T):
    d1, d2 = d1d2(S, K, r, sigma, T)
    return {
        'delta': ncdf(d1),
        'gamma': npdf(d1) / (S * sigma * math.sqrt(T)),
        'vega': S * npdf(d1) * math.sqrt(T),
        'theta': -S * npdf(d1) * sigma / (2 * math.sqrt(T)) - r * K * math.exp(-r * T) * ncdf(d2),
        'rho': K * T * math.exp(-r * T) * ncdf(d2),
    }


# ------------------------------------------------------------- rivals

def crr_call(S, K, r, sigma, T, n):
    dt = T / n
    u = math.exp(sigma * math.sqrt(dt))
    d = 1 / u
    p = (math.exp(r * dt) - d) / (u - d)
    disc = math.exp(-r * dt)
    values = [max(S * u ** j * d ** (n - j) - K, 0.0) for j in range(n + 1)]
    for step in range(n, 0, -1):
        values = [disc * (p * values[j + 1] + (1 - p) * values[j]) for j in range(step)]
    return values[0], (n + 1) * (n + 2) // 2


def crank_nicolson_call(S, K, r, sigma, T, m, n, smax_mult=4.0):
    """Crank-Nicolson on the Black-Scholes PDE in S, m price steps on
    [0, smax], n time steps, Dirichlet boundaries; linear interpolation
    at S. Returns (price, grid points)."""
    smax = smax_mult * K
    ds = smax / m
    dt = T / n
    grid = [i * ds for i in range(m + 1)]
    v = [max(s - K, 0.0) for s in grid]
    # coefficients for interior nodes i = 1..m-1
    a = [0.0] * (m + 1)
    b = [0.0] * (m + 1)
    c = [0.0] * (m + 1)
    for i in range(1, m):
        s = grid[i]
        alpha = 0.5 * sigma * sigma * s * s / (ds * ds)
        beta = r * s / (2 * ds)
        a[i] = 0.5 * dt * (alpha - beta)
        b[i] = -0.5 * dt * (2 * alpha + r)
        c[i] = 0.5 * dt * (alpha + beta)
    for step in range(1, n + 1):
        tau = step * dt
        rhs = [0.0] * (m + 1)
        for i in range(1, m):
            rhs[i] = a[i] * v[i - 1] + (1 + b[i]) * v[i] + c[i] * v[i + 1]
        lower = smax - K * math.exp(-r * tau)
        rhs[0] = 0.0
        rhs[m] = lower
        # tridiagonal solve: -a v_{i-1} + (1 - b) v_i - c v_{i+1} = rhs
        sub = [-a[i] for i in range(m + 1)]
        diag = [1 - b[i] for i in range(m + 1)]
        sup = [-c[i] for i in range(m + 1)]
        diag[0] = 1.0
        sup[0] = 0.0
        diag[m] = 1.0
        sub[m] = 0.0
        # Thomas algorithm
        cp = [0.0] * (m + 1)
        dp = [0.0] * (m + 1)
        cp[0] = sup[0] / diag[0]
        dp[0] = rhs[0] / diag[0]
        for i in range(1, m + 1):
            denom = diag[i] - sub[i] * cp[i - 1]
            cp[i] = sup[i] / denom if i < m else 0.0
            dp[i] = (rhs[i] - sub[i] * dp[i - 1]) / denom
        v = [0.0] * (m + 1)
        v[m] = dp[m]
        for i in range(m - 1, -1, -1):
            v[i] = dp[i] - cp[i] * v[i + 1]
    i = int(S / ds)
    w = (S - grid[i]) / ds
    return (1 - w) * v[i] + w * v[i + 1], (m + 1) * (n + 1)


def monte_carlo_call(S, K, r, sigma, T, paths, rng):
    disc = math.exp(-r * T)
    drift = (r - 0.5 * sigma * sigma) * T
    vol = sigma * math.sqrt(T)
    total = 0.0
    total_sq = 0.0
    for _ in range(paths):
        z = rng.gauss(0.0, 1.0)
        payoff = max(S * math.exp(drift + vol * z) - K, 0.0)
        total += payoff
        total_sq += payoff * payoff
    mean = total / paths
    var = total_sq / paths - mean * mean
    return disc * mean, disc * math.sqrt(var / paths)


def implied_vol(price, S, K, r, T, lo=1e-6, hi=5.0):
    """Brent's method (puzzle 167) inverting the call formula in sigma."""
    f = lambda s: bs_call(S, K, r, s, T) - price
    a, b = lo, hi
    fa, fb = f(a), f(b)
    if fa * fb > 0:
        return None
    c, fc = a, fa
    d = e = b - a
    eps = 2.220446049250313e-16
    for _ in range(200):
        if (fb > 0) == (fc > 0):
            c, fc = a, fa
            d = e = b - a
        if abs(fc) < abs(fb):
            a, fa, b, fb, c, fc = b, fb, c, fc, b, fb
        tol1 = 2 * eps * abs(b) + 0.5e-12
        m = 0.5 * (c - b)
        if abs(m) <= tol1 or fb == 0:
            return b
        if abs(e) >= tol1 and abs(fa) > abs(fb):
            s = fb / fa
            if a == c:
                p, q = 2 * m * s, 1 - s
            else:
                q = fa / fc
                rr = fb / fc
                p = s * (2 * m * q * (q - rr) - (b - a) * (rr - 1))
                q = (q - 1) * (rr - 1) * (s - 1)
            if p > 0:
                q = -q
            else:
                p = -p
            if 2 * p < min(3 * m * q - abs(tol1 * q), abs(e * q)):
                e, d = d, p / q
            else:
                d = e = m
        else:
            d = e = m
        a, fa = b, fb
        b += d if abs(d) > tol1 else (tol1 if m > 0 else -tol1)
        fb = f(b)
    return b


def heston_call_prices(S, r, T, strikes, rng, paths, steps, v0=0.04, kappa=1.5, theta=0.04, xi=0.6, rho=-0.7):
    """Monte Carlo under Heston stochastic volatility (full truncation
    Euler), all strikes priced on the same paths."""
    dt = T / steps
    sums = [0.0] * len(strikes)
    sums_sq = [0.0] * len(strikes)
    sq_dt = math.sqrt(dt)
    rho_c = math.sqrt(1 - rho * rho)
    for _ in range(paths):
        s = S
        v = v0
        for _ in range(steps):
            z1 = rng.gauss(0.0, 1.0)
            z2 = rho * z1 + rho_c * rng.gauss(0.0, 1.0)
            vp = max(v, 0.0)
            s *= math.exp((r - 0.5 * vp) * dt + math.sqrt(vp) * sq_dt * z1)
            v += kappa * (theta - vp) * dt + xi * math.sqrt(vp) * sq_dt * z2
        for i, k in enumerate(strikes):
            pay = max(s - k, 0.0)
            sums[i] += pay
            sums_sq[i] += pay * pay
    disc = math.exp(-r * T)
    out = []
    for i in range(len(strikes)):
        mean = sums[i] / paths
        var = sums_sq[i] / paths - mean * mean
        out.append((disc * mean, disc * math.sqrt(var / paths)))
    return out


def up_and_out_call_mc(S, K, r, sigma, T, barrier, rng, paths, steps):
    dt = T / steps
    drift = (r - 0.5 * sigma * sigma) * dt
    vol = sigma * math.sqrt(dt)
    disc = math.exp(-r * T)
    total = 0.0
    total_sq = 0.0
    for _ in range(paths):
        s = S
        alive = True
        for _ in range(steps):
            s *= math.exp(drift + vol * rng.gauss(0.0, 1.0))
            if s >= barrier:
                alive = False
                break
        pay = max(s - K, 0.0) if alive else 0.0
        total += pay
        total_sq += pay * pay
    mean = total / paths
    var = total_sq / paths - mean * mean
    return disc * mean, disc * math.sqrt(var / paths)


def main():
    rng = random.Random(SEED)
    S, K, r, sigma, T = S0, K0, R0, SIG0, T0
    call = bs_call(S, K, r, sigma, T)
    put = bs_put(S, K, r, sigma, T)
    assert abs(call - 10.450583572185565) < 1e-9, call
    assert abs(put - 5.573526022256971) < 1e-9, put

    # Oracle 1: the PDE at a grid of points, and the boundaries.
    worst = 0.0
    for s in (60.0, 80.0, 100.0, 120.0, 150.0):
        for tau in (0.1, 0.5, 1.0, 2.0):
            h = 1e-4 * s  # small enough that the fourth-derivative truncation error is negligible at the money near expiry
            k = 1e-4
            v = lambda ss, tt: bs_call(ss, K, r, sigma, tt)
            v_t = -(v(s, tau + k) - v(s, tau - k)) / (2 * k)  # time to expiry runs backward
            v_s = (v(s + h, tau) - v(s - h, tau)) / (2 * h)
            v_ss = (v(s + h, tau) - 2 * v(s, tau) + v(s - h, tau)) / (h * h)
            residual = v_t + 0.5 * sigma * sigma * s * s * v_ss + r * s * v_s - r * v(s, tau)
            worst = max(worst, abs(residual))
    assert worst < 5e-5, worst
    assert abs(bs_call(S, K, r, sigma, 1e-12) - max(S - K, 0.0)) < 1e-4  # at the money the limit is approached, not hit
    assert abs(bs_call(110.0, K, r, sigma, 1e-12) - 10.0) < 1e-6
    assert abs(bs_call(120, K, r, 1e-9, T) - (120 - K * math.exp(-r * T))) < 1e-6
    assert bs_call(1e-6, K, r, sigma, T) < 1e-12
    assert abs(bs_call(1e4, K, r, sigma, T) - (1e4 - K * math.exp(-r * T))) < 1e-6

    # Oracle 2: parity and the Greeks.
    parity = call - put - (S - K * math.exp(-r * T))
    assert abs(parity) < 1e-12, parity
    g = greeks_call(S, K, r, sigma, T)
    h = 1e-3
    fd = {
        'delta': (bs_call(S + h, K, r, sigma, T) - bs_call(S - h, K, r, sigma, T)) / (2 * h),
        'gamma': (bs_call(S + h, K, r, sigma, T) - 2 * call + bs_call(S - h, K, r, sigma, T)) / (h * h),
        'vega': (bs_call(S, K, r, sigma + 1e-5, T) - bs_call(S, K, r, sigma - 1e-5, T)) / 2e-5,
        'theta': -(bs_call(S, K, r, sigma, T + 1e-5) - bs_call(S, K, r, sigma, T - 1e-5)) / 2e-5,
        'rho': (bs_call(S, K, r + 1e-5, sigma, T) - bs_call(S, K, r - 1e-5, sigma, T)) / 2e-5,
    }
    for name in g:
        assert abs(g[name] - fd[name]) < 1e-4 * max(1, abs(g[name])), (name, g[name], fd[name])

    # Oracle 3: the numerical rivals.
    rows = []
    for n in (100, 1000, 4000):
        price, work = crr_call(S, K, r, sigma, T, n)
        rows.append((f'CRR lattice, N = {n:,}', price, abs(price - call), None, f'{work:,} nodes'))
    cn_errors = {}
    for m, n in ((200, 200), (800, 800)):
        price, work = crank_nicolson_call(S, K, r, sigma, T, m, n)
        cn_errors[m] = abs(price - call)
        rows.append((f'Crank-Nicolson, {m} x {n}', price, abs(price - call), None, f'{work:,} grid points'))
    mc_rows = {}
    for paths in (10_000, 100_000):
        price, se = monte_carlo_call(S, K, r, sigma, T, paths, random.Random(SEED + paths))
        mc_rows[paths] = (price, se)
        rows.append((f'Monte Carlo, {paths:,} paths', price, abs(price - call), se, f'{paths:,} paths'))
    crr_100 = rows[0][2]
    crr_4000 = rows[2][2]
    assert crr_4000 < crr_100 / 20, (crr_100, crr_4000)
    assert crr_4000 < 1e-3
    assert cn_errors[800] < cn_errors[200] and cn_errors[800] < 1e-3, cn_errors
    for paths, (price, se) in mc_rows.items():
        assert abs(price - call) < 3 * se, (paths, price, se, call)
    assert mc_rows[100_000][1] < mc_rows[10_000][1] / 2.5

    # Oracle 4: implied volatility round trips, and the Heston smile.
    worst_iv = 0.0
    for k in (60.0, 80.0, 100.0, 120.0, 140.0):
        price = bs_call(S, k, r, sigma, T)
        iv = implied_vol(price, S, k, r, T)
        worst_iv = max(worst_iv, abs(iv - sigma))
    assert worst_iv < 1e-8, worst_iv
    strikes = [80.0, 90.0, 100.0, 110.0, 120.0]
    heston = heston_call_prices(S, r, T, strikes, random.Random(SEED + 7), paths=20_000, steps=100)
    smile = []
    for (price, se), k in zip(heston, strikes):
        iv = implied_vol(price, S, k, r, T)
        iv_lo = implied_vol(price - 2 * se, S, k, r, T)
        iv_hi = implied_vol(price + 2 * se, S, k, r, T)
        smile.append((k, price, se, iv, iv_lo, iv_hi))
    # the model with negative correlation makes low strikes dearer in
    # volatility than high strikes: the skew must be larger than the
    # Monte Carlo uncertainty of both ends
    assert smile[0][4] > smile[-1][5], smile
    # the Black-Scholes "smile" from its own prices is flat by construction
    flat = [implied_vol(bs_call(S, k, r, sigma, T), S, k, r, T) for k in strikes]
    assert max(flat) - min(flat) < 1e-8

    # Oracle 5: the vanilla formula on a barrier contract.
    barrier = 120.0
    knock, knock_se = up_and_out_call_mc(S, K, r, sigma, T, barrier, random.Random(SEED + 11), paths=40_000, steps=252)
    assert call > 5 * knock, (call, knock)

    print('contest: a European call, S = 100, K = 100, r = 5%, sigma = 20%, T = 1 year; referee: the closed form itself, checked against the PDE it must satisfy, put-call parity, and the analytic Greeks against finite differences; one currency: work (nodes, grid points, paths)')
    print(f'closed form: call {call:.6f}, put {put:.6f}; parity C - P - (S - K e^(-rT)) = {parity:.1e}; PDE residual over 20 (S, T) points at most {worst:.1e}')
    print('Greeks, analytic vs central difference: ' + ', '.join(f'{k} {g[k]:.5f} / {fd[k]:.5f}' for k in g))
    print(f'{"method":>28} {"price":>10} {"error":>9} {"std err":>8}  work')
    print(f'{"Black-Scholes closed form":>28} {call:>10.5f} {0:>9.5f} {"":>8}  2 normal cdf evaluations')
    for name, price, err, se, work in rows:
        print(f'{name:>28} {price:>10.5f} {err:>9.5f} {"" if se is None else f"{se:.4f}":>8}  {work}')
    print('implied volatility by Brent: round trip within ' + f'{worst_iv:.1e}' + ' at strikes 60 to 140; Black-Scholes prices invert to a flat 20.0% at every strike')
    print('Heston prices (20,000 paths, 100 steps, kappa 1.5, theta 0.04, xi 0.6, rho -0.7) inverted through Black-Scholes: '
          + '; '.join(f'K = {k:.0f}: {iv * 100:.1f}% ({lo * 100:.1f} to {hi * 100:.1f})' for k, _, _, iv, lo, hi in smile))
    print(f'the barrier: up-and-out call, barrier 120, daily monitoring, Monte Carlo {knock:.3f} (std err {knock_se:.3f}) against the vanilla formula {call:.3f}, {call / knock:.1f}x too high')
    print(f'OK: closed form {call:.4f} satisfies the PDE to {worst:.0e}, parity to {abs(parity):.0e}, Greeks to 1e-4 relative; CRR within {crr_4000:.4f} at 4,000 steps, Crank-Nicolson within {cn_errors[800]:.4f} at 800 x 800, Monte Carlo within 3 standard errors; '
          f'implied vol round trip {worst_iv:.0e}; the Heston skew {smile[0][3] * 100:.1f}% at K = 80 against {smile[-1][3] * 100:.1f}% at K = 120 is what a constant volatility cannot make; the vanilla formula overprices the barrier call {call / knock:.1f}x')


if __name__ == '__main__':
    main()
